"""Reproduce the licensed HOLM headline face; never alter the original variable font."""
import argparse
import hashlib
import io
import json
from importlib.metadata import version
from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont


def digest(data):
    return hashlib.sha256(data).hexdigest()


parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[2])
parser.add_argument('--output', type=Path)
parser.add_argument('--check', action='store_true', help='Verify bytes and glyph geometry without writing')
args = parser.parse_args()
recipe = json.loads((Path(__file__).parent / 'holm-headline-recipe.json').read_text())
assert version('fonttools') == recipe['fontTools'], 'Install the pinned font requirements'
assert version('brotli') == recipe['brotli'], 'Install the pinned font requirements'
source = args.root / recipe['source']
assert digest(source.read_bytes()) == recipe['sourceSha256'], 'Source font changed; review the recipe'
assert digest((args.root / recipe['license']).read_bytes().replace(b'\r\n', b'\n')) == recipe['licenseSha256'], 'License changed'
original = TTFont(source, recalcTimestamp=False)
candidate = instantiateVariableFont(original, {'wght': 400, 'opsz': (40, 40, 72)}, inplace=False)
assert candidate.getBestCmap() == original.getBestCmap(), 'Character coverage changed'
assert len(candidate.getBestCmap()) == recipe['mappedCharacters']
assert [(axis.axisTag, axis.minValue, axis.defaultValue, axis.maxValue) for axis in candidate['fvar'].axes] == [('opsz', 40, 40, 72)]
buffer = io.BytesIO()
candidate.save(buffer)
data = buffer.getvalue()
assert len(data) == recipe['bytes']
assert digest(data) == recipe['candidateSha256'], 'Generated bytes differ from the reviewed artifact'
output = args.output or args.root / recipe['candidate']
if args.check:
    assert output.read_bytes() == data, 'Checked-in font does not match the recipe'
    # Restricting an axis can quantize deltas. Keep the maximum under one source font unit.
    for optical_size in [40, 48, 60, 72]:
        expected = instantiateVariableFont(TTFont(source, recalcTimestamp=False), {'wght': 400, 'opsz': optical_size}, inplace=True)
        actual = instantiateVariableFont(TTFont(io.BytesIO(data), recalcTimestamp=False), {'opsz': optical_size}, inplace=True)
        for glyph in expected.getGlyphOrder():
            assert abs(expected['hmtx'][glyph][0] - actual['hmtx'][glyph][0]) <= 1
            left = expected['glyf'][glyph].getCoordinates(expected['glyf'])[0]
            right = actual['glyf'][glyph].getCoordinates(actual['glyf'])[0]
            assert len(left) == len(right)
            assert all(max(abs(a[0]-b[0]), abs(a[1]-b[1])) <= 1 for a, b in zip(left, right))
    print('Headline font is reproducible; all characters, optical-size bounds and glyph geometry verified.')
else:
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(data)
    print(f'Wrote {len(data)} bytes to {output}')
